function pricePath(start: number, percentageMoves: number[]) {
  return percentageMoves.reduce<number[]>((prices, move) => {
    const last = prices[prices.length - 1];
    return [...prices, Number((last * (1 + move / 100)).toFixed(2))];
  }, [start]);
}

