export const syntheticStockSectors = [...new Set(syntheticStockProfiles.map((profile) => profile.sector))];

export function getSyntheticStockProfile(idOrSymbol: string) {
  const normalized = idOrSymbol.trim().toLowerCase();
  return syntheticStockProfiles.find((profile) => profile.id === normalized || profile.symbol.toLowerCase() === normalized);
}

export function searchSyntheticStockProfiles(query: string, sector = "All") {
  const normalized = query.trim().toLowerCase();
  return syntheticStockProfiles.filter((profile) => {
    const matchesSector = sector === "All" || profile.sector === sector;
    const searchable = [profile.name, profile.symbol, profile.sector, profile.industry, profile.businessDescription, ...profile.relatedTopics].join(" ").toLowerCase();
    return matchesSector && (!normalized || searchable.includes(normalized));
  });
}
